export const MAPS_BY_ID = Object.fromEntries(MAP_CATALOG.map((m) => [m.id, m]));

/** The lobby format of a map, as matches.js names formats: '1v1', '2v2', '3v3', or 'ffa3' / 'ffa4' for free-for-all. */
export const mapMode = (m) => (m.players === m.teamSize * 2 ? `${m.teamSize}v${m.teamSize}` : `ffa${m.players}`);

/** The lobby's view of the catalog: what a client needs to offer, describe and draw a map. */
export function mapList() {
  return [{ id: 'random', name: 'Random', players: 0, teamSize: 0, size: 0, description: 'A new procedurally generated world for any number of players.' },
    ...MAP_CATALOG.map((m) => ({ id: m.id, name: m.name, players: m.players, teamSize: m.teamSize, size: m.size, mode: mapMode(m),
      ffa: m.players !== m.teamSize * 2, description: m.description, preview: MAP_PREVIEWS[m.id] || null }))];
}
