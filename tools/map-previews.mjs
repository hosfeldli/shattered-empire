// Regenerates server/sim/mapPreviews.js: the lobby preview grid of every authored map (format in
// actionMap.js, mapPreview). Each map is built in its own worker thread, because the map size is fixed
// per process. Usage: node tools/map-previews.mjs [--ascii] [mapId...]
//   --ascii prints each preview as text instead of writing the file (one character per cell, rows halved).
import fs from 'node:fs';
import { Worker } from 'node:worker_threads';
import { MAP_CATALOG } from '../server/sim/mapCatalog.js';
import { MAP_PREVIEWS } from '../server/sim/mapPreviews.js';

const SIM = new URL('../server/sim/', import.meta.url).href;
const args = process.argv.slice(2);
const ascii = args.includes('--ascii');
const only = args.filter((a) => !a.startsWith('--'));
const probe = `
const { parentPort, workerData } = await import('node:worker_threads');
globalThis.SE_MAP_SIZE = workerData.size; globalThis.SE_WRAP = false;
const { ActionGame } = await import(workerData.sim + 'actionGame.js');
const { mapPreview } = await import(workerData.sim + 'actionMap.js');
const slots = Array.from({ length: workerData.players }, () => ({ human: false, difficulty: 'normal' }));
const g = new ActionGame({ id: 'preview', seed: 1, map: workerData.id, slots });
parentPort.postMessage(mapPreview(g));
`;
export function buildPreview(def) {
  return new Promise((resolve, reject) => {
    const worker = new Worker(probe, { eval: true, type: 'module', workerData: { size: def.size, id: def.id, players: def.players, sim: SIM } });
    worker.once('message', (m) => { resolve(m); worker.terminate(); });
    worker.once('error', reject);
  });
}

const GLYPH = ['~', '-', '.', 'f', ',', 'h', 'M', 'A', '=', ':', '#', 'H'];
export function previewAscii(p) {
  const cells = Buffer.from(p.cells, 'base64'), grid = [];
  for (let r = 0; r < p.h; r++) grid.push([...cells.subarray(r * p.w, (r + 1) * p.w)].map((c) => GLYPH[c] ?? '?'));
  const put = (u, v, ch) => { const r = Math.min(p.h - 1, Math.floor(v * p.h)), c = Math.min(p.w - 1, Math.floor(u * p.w)); grid[r][c] = ch; };
  for (const o of p.outposts) put(o.u, o.v, 'o');
  for (const b of p.bases) put(b.u, b.v, 'B');
  for (const s of p.starts) put(s.u, s.v, String(s.seat));
  return grid.filter((_, r) => r % 2 === 0).map((row) => row.join('')).join('\n');
}

if (import.meta.url === new URL(`file:///${process.argv[1].replace(/\\/g, '/')}`).href || process.argv[1]?.endsWith('map-previews.mjs')) {
  const maps = MAP_CATALOG.filter((m) => !only.length || only.includes(m.id));
  const out = {};
  for (const def of maps) {
    out[def.id] = await buildPreview(def);
    if (ascii) console.log(`${def.name} (${def.id}, ${def.size}, ${def.players} players)\n${previewAscii(out[def.id])}\n`);
  }
  if (!ascii) {
    const file = new URL('../server/sim/mapPreviews.js', import.meta.url);
    // previews of maps not rebuilt this run are kept; maps no longer in the catalog are dropped
    const all = Object.fromEntries(MAP_CATALOG.map((m) => [m.id, out[m.id] || MAP_PREVIEWS[m.id]]).filter(([, p]) => p));
    const body = Object.entries(all).map(([id, p]) => `  ${id}: ${JSON.stringify(p)},`).join('\n');
    fs.writeFileSync(file, `// Generated by tools/map-previews.mjs: do not edit by hand. Format: mapPreview in actionMap.js.\nexport const MAP_PREVIEWS = {\n${body}\n};\n`);
    console.log(`rebuilt ${Object.keys(out).length}, wrote ${Object.keys(all).length} previews to server/sim/mapPreviews.js`);
  }
}
